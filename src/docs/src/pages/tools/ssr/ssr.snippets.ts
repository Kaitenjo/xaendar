export const BROWSER_GLOBALS: SourceFile = {
  name: 'theme-toggle.xd.component.ts',
  lang: 'ts',
  code: `import { CustomElement, WebComponent } from '@xaendar/core';
import { signal } from '@xaendar/core/signals';

/**
 * Switches the theme of the page, which the browser remembers.
 */
@WebComponent({
  selector: 'theme-toggle',
  templateUrl: './theme-toggle.xd.component.html'
})
export class ThemeToggleComponent extends CustomElement {
  /**
   * The theme shown: the light one, on the server and until the browser reads the remembered one.
   */
  public readonly theme = signal('light');

  constructor() {
    super();
    // An effect runs in the browser only: localStorage exists there
    this.effect(() => this.theme.set(localStorage.getItem('theme') ?? 'light'));
  }

  public onInit(): void {
    // onInit runs on the server too, where document is not defined
    if (typeof document !== 'undefined') {
      document.documentElement.dataset.theme = this.theme();
    }
  }
}`
};

