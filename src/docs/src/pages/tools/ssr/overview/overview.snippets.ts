export const RENDER_INPUTS: SourceFile = {
  name: 'entry-server.ts',
  lang: 'ts',
  code: `// A page per route: the product of /products/42 rendered with the input it reads
const { renderToString } = await import('@xaendar/ssr');
const { ProductPageComponent } = await import('./product-page/product-page.xd.component');
const { MyAppRootComponent } = await import('./my-app-root/my-app-root.xd.component');

/**
 * Renders the page of a URL on the server.
 *
 * @param url - The path of the page, with its query string.
 * @returns The HTML of the component of the page.
 */
export function render(url: string): Promise<string> {
  // Any base keeps url on its origin: only its path is read
  const { pathname } = new URL(url, 'http://localhost');
  const productId = /^\\/products\\/(\\w+)$/.exec(pathname)?.[1];
  // The inputs are named like their property, and typed by it: { productId: 42 } fails the type check
  return productId ? renderToString(ProductPageComponent, { productId }) : renderToString(MyAppRootComponent);
}`
};

