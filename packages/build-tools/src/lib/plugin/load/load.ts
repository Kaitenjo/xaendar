import { type ASTNode, ASTNodeType, type ContextCache, type ImportNode, parseTemplate } from '@xaendar/compiler';
import { getTemplateWarnings } from '@xaendar/language-core';
import { dirname } from 'node:path';
import { registerMetadata } from '../../registry/metadata-registry/metadata-registry';
import type { XaendarPluginStrategy } from '../../types/plugin-strategy.type';
import type { XaendarPluginState } from '../../types/xaendar-plugin-state.type';
import type { StyleCompileResult } from '../../types/style-compile-result.type';
import { TemplateModuleRequest } from '../../types/template-module-request.type';
import { describeTemplateWarning, extractImportedComponentPaths, getImportOrExtract, getMetadataOrExtract, parseStyleModuleId, parseTemplateModuleId, resolveTemplateModules } from '../plugin-utils/plugin.utils';
import { compileStyle } from '../style/compile-style';
import { minifyCss } from '../style/minify-css/minify-css.utils';
import type { LoadHook } from '../../types/load-hook.type';
import { findWorkspaceLibrary, markClientOnly } from '../../utils/workspace-libraries/workspace-libraries.utils';

/**
 * Compiles a template into the module exporting its render function, and a style
 * file into the module exporting its stylesheet.
 *
 * Each module is requested (and therefore compiled) only by components that are
 * part of the module graph, and exactly once for every template/signals pair or
 * style file, no matter how many components share it.
 *
 * The modules are compiled and generated by the strategy of the environment (see `XaendarPluginState['strategies']`):
 * for the rendering on the server, the same module exports the render function writing the HTML of the template,
 * compiled by `@xaendar/ssr-compiler`, and the text of the stylesheet.
 *
 * The warnings of a template about what the server cannot read are reported to the terminal, from the environment of
 * the server, once per template.
 */
export function createLoadHook(state: XaendarPluginState): LoadHook {
  return async function load(this, id) {
    const stylePath = parseStyleModuleId(id);
    if (stylePath !== undefined) {
      return loadStyleModule(this, stylePath, state.strategies[this.environment.config.consumer]);
    }

    const request = parseTemplateModuleId(id);
    if (request) {
      return loadTemplateModule(this, request, state.strategies[this.environment.config.consumer]);
    }

    return null;
}

/**
 * Compiles a style file into the module exporting its stylesheet, watching every file the
 * compiled CSS depends on: editing any of them invalidates the module.
 *
 * @param context - The context of the hook.
 * @param stylePath - The path of the style file.
 * @param strategy - The functions generating the module: for the browser, exporting a `CSSStyleSheet`, or for the
 * server rendering, exporting the text of the CSS.
 * @returns The module.
 * @throws The error of `context.error` when the style file cannot be compiled.
 */
async function loadStyleModule(context: ThisParameterType<LoadHook>, stylePath: string, strategy: XaendarPluginStrategy): Promise<ReturnType<LoadHook>> {
  let styleResult: StyleCompileResult;
  try {
    styleResult = await compileStyle(stylePath, state.host);
    if (state.minifyStyles && styleResult.cssText) {
      styleResult.cssText = minifyCss(styleResult.cssText, stylePath);
    }
  } catch (err) {
    return context.error(`Failed to compile style - ${stylePath}\n${err}`);
  }

  for (let i = 0; i < styleResult.dependencyPaths.length; i++) {
    context.addWatchFile(styleResult.dependencyPaths[i]);
  }

  // See the template module about the empty mappings map.
  return {
    code: strategy.generateStyleModule(styleResult.cssText),
    map: { mappings: '' },
    moduleType: 'js'
  };
}

/**
 * Compiles a template into the module exporting its render function, watching the template and the components it
 * imports: editing any of them invalidates the module.
 *
 * @param context - The context of the hook.
 * @param request - The template module request, with the path of the template and the members of its components.
 * @param strategy - The functions compiling the template and generating the module: for the browser, or for the server
 * rendering, whose render function writes the HTML of the template.
 * @returns The module.
 * @throws The error of `context.error` when the template cannot be found or compiled.
 */
async function loadTemplateModule(context: ThisParameterType<LoadHook>, request: TemplateModuleRequest, strategy: XaendarPluginStrategy): Promise<ReturnType<LoadHook>> {
   const { templatePath, signals, shadowingMembers } = request;

    /*
      Watching the template, and the components it imports whose metadata shape the generated bindings,
      links them to this module: editing any of them invalidates the compiled render function.
    */
    context.addWatchFile(templatePath);
    const templateSource = state.host.readFile(templatePath);
    if (templateSource === undefined) {
      return context.error(`Could not find template at ${templatePath}`);
    }

    // The symbols the template imports are imported by the render code, resolved against the directory of the template
    const templateDir = dirname(templatePath);

    /*
      Watching all the modules imported in the template, and linking them to this module: editing any of them
      invalidates the compiled render function. They are watched before the template is compiled, so that fixing the one
      making it fail compiles it again.
    */
    const importedPaths = extractImportedComponentPaths(templateSource, templateDir, state.compilerOptions);
    for (let i = 0; i < importedPaths.length; i++) {
      const importedPath = importedPaths[i];
      if (state.host.fileExists(importedPath)) {
        context.addWatchFile(importedPath);
      }
    }

    const cache: ContextCache = {
      getOrInsert: (classNameOrSelector, path) => getMetadataOrExtract(classNameOrSelector, path, state.compilerOptions),
      // The server renders the components of a library that does not render there as an application does with its build
      getImport: async (imported, local, baseDir, path) => markClientOnly(await getImportOrExtract(imported, local, baseDir, path, state.compilerOptions), state.libraries),
      set: registerMetadata
    };
    // A template of a library of the workspace is compiled with the options of the library
    const customElements = findWorkspaceLibrary(state.libraries, templatePath)?.customElements ?? state.customElements;

    let nodes: ASTNode[];
    let compiledFunctions: string;
    let dependencies: readonly string[];
    try {
      nodes = parseTemplate(templateSource);
      /*
        The modules the template imports are imported by its module too, so the bundler keeps them in the chunk graph
        of the template: the files declaring the components and the directives, also the ones imported through a
        barrel, which the paths of the `@import`s do not lead to. The ones of `@import lazy` are not: something else
        loads them on demand.
      */
      const modules = await resolveTemplateModules(nodes.filter((node): node is ImportNode => node.type === ASTNodeType.Import), templateDir, cache, state.host);
      for (let i = 0; i < modules.watched.length; i++) {
        context.addWatchFile(modules.watched[i]);
      }

      dependencies = modules.imported;
      compiledFunctions = await strategy.compile(templateSource, { signals, templateDir, shadowingMembers, customElements, cache, islands: state.staticComponents?.islands.get(templatePath) });
      if (strategy.filterDependencies) {
        dependencies = await strategy.filterDependencies(templateSource, dependencies, { templateDir, cache });
      }
    } catch (err) {
      return context.error(`Failed to compile template - ${templatePath}\n${err}`);
    }

    if (strategy.server) {
      const warnings = getTemplateWarnings(nodes, shadowingMembers);
      for (let i = 0; i < warnings.length; i++) {
        context.warn(`${templatePath}\n${describeTemplateWarning(templateSource, warnings[i])}`);
      }
    }

    /*
      An empty mappings map marks the module as having no original source. Without it, Vite would generate
      a sourcemap treating this generated JS as the original source, named after the template path and
      shown by DevTools as a fake `.html` file.
      TODO: replace it with a real sourcemap from the generated code back to the template.
    */
    return {
      code: strategy.generateTemplateModule(compiledFunctions, dependencies),
      map: { mappings: '' },
      moduleType: 'js'
    };
  };
}